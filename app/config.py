# ── In-memory cache ────────────────────────────────────────────────────────────

_cache: dict = {}


def get(key: str, fallback: Any = None) -> str:
    if key in _cache:
        return _cache[key]
    return DEFAULTS.get(key, fallback)


def get_int(key: str) -> int:
    return int(get(key))


def get_float(key: str) -> float:
    return float(get(key))


def get_json(key: str) -> Any:
    return json.loads(get(key))


def all_with_defaults() -> dict:
    result = dict(DEFAULTS)
    result.update(_cache)
    return result


async def load(db_path: str):
    import aiosqlite
    try:
        async with aiosqlite.connect(db_path) as db:
            async with db.execute("SELECT key, value FROM settings") as cursor:
                rows = await cursor.fetchall()
        _cache.clear()
        _cache.update({k: v for k, v in rows})
    except Exception:
        pass


async def save_all(updates: dict, db_path: str):
    import aiosqlite
    async with aiosqlite.connect(db_path) as db:
        for k, v in updates.items():
            await db.execute(
                "INSERT INTO settings (key, value, updated_at)"
                " VALUES (?, ?, datetime('now'))"
                " ON CONFLICT(key) DO UPDATE SET value=excluded.value, updated_at=datetime('now')",
                (k, v),
            )
        await db.commit()
    _cache.update(updates)
